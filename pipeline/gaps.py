"""Compare poll-implied and market-implied chances race by race, and flag large gaps.

Reads data/polls_races.csv and data/markets_races.csv (run fetch_markets.py and
fetch_polls.py first). Both sides are expressed as the chance that the
non-Republican side wins (the Democrat; in Nebraska the independent), so
Nebraska compares like with like.

Writes
    data/gaps.csv               every race with both polls and markets
    research/gaps_report.md     the flagged races, with automatic hints for the manual review

    python -I pipeline/gaps.py
"""

import csv
from collections import defaultdict
from datetime import date
from pathlib import Path
from statistics import NormalDist

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
REPORT = ROOT / "research" / "gaps_report.md"

FLAG = 0.15    # gap in probability that triggers a manual review
WATCH = 0.08   # smaller gaps worth keeping an eye on
N = NormalDist()


def read(path):
    return list(csv.DictReader(path.open(encoding="utf-8")))


def market_consensus(rows):
    """Volume-weighted chance of a non-Republican win across venues, per race."""
    by_race = defaultdict(list)
    for r in rows:
        if r["p_rep"]:
            by_race[r["race_id"]].append(r)
    out = {}
    for race, rs in by_race.items():
        vol = [max(float(r["volume_usd"]), 1.0) for r in rs]
        p = [1 - float(r["p_rep"]) for r in rs]
        venues = {r["venue"]: 1 - float(r["p_rep"]) for r in rs}
        spreads = [float(r["max_spread"]) for r in rs if r["max_spread"]]
        out[race] = {
            "p_market": sum(v * x for v, x in zip(vol, p)) / sum(vol),
            "volume": sum(float(r["volume_usd"]) for r in rs),
            "venues": venues,
            "max_spread": max(spreads) if spreads else None,
        }
    return out


def hints(row):
    h = []
    if row["n_eff"] < 2:
        h.append("few polls")
    if (date.today() - date.fromisoformat(row["latest_poll"])).days > 21:
        h.append("polls older than 3 weeks")
    if row["share_partisan_weight"] >= 0.25:
        h.append("partisan polls carry ≥25% of weight")
    if row["market_volume"] < 100_000:
        h.append("thin market (<$100k traded)")
    if row["venue_gap"] is not None and row["venue_gap"] >= 0.05:
        h.append("Kalshi and Polymarket differ by ≥5 pts")
    return "; ".join(h)


def main():
    polls = {r["race_id"]: r for r in read(DATA / "polls_races.csv") if r["race_id"] != "GENERIC"}
    markets = market_consensus(read(DATA / "markets_races.csv"))

    rows = []
    for race, pr in polls.items():
        m = markets.get(race)
        if not m:
            continue
        p_poll = float(pr["p_nonrep"])
        p_mkt = min(max(m["p_market"], 0.001), 0.999)
        sd = float(pr["sd"])
        venue_vals = list(m["venues"].values())
        row = {
            "race_id": race,
            "p_polls": round(p_poll, 3),
            "p_market": round(p_mkt, 3),
            "gap": round(p_poll - p_mkt, 3),
            "poll_margin": float(pr["margin_nonrep"]),
            # The margin the market price implies, on the same error scale as the polls.
            "market_implied_margin": round(sd * N.inv_cdf(p_mkt), 1),
            "n_polls": int(pr["n_polls"]),
            "n_polls_45d": int(pr["n_polls_45d"]),
            "n_eff": float(pr["n_eff"]),
            "latest_poll": pr["latest_end"],
            "share_partisan_weight": float(pr["share_partisan_weight"]),
            "market_volume": round(m["volume"]),
            "venue_gap": round(max(venue_vals) - min(venue_vals), 3) if len(venue_vals) > 1 else None,
            "kalshi": m["venues"].get("kalshi"),
            "polymarket": m["venues"].get("polymarket"),
        }
        row["status"] = "FLAG" if abs(row["gap"]) >= FLAG else "watch" if abs(row["gap"]) >= WATCH else "ok"
        row["hints"] = hints(row)
        rows.append(row)
    rows.sort(key=lambda r: -abs(r["gap"]))

    with (DATA / "gaps.csv").open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    def side(p):
        return f"{p:.0%}"

    def margin(x):
        return ("D+" if x >= 0 else "R+") + f"{abs(x):.1f}"

    lines = [
        "# Where polls and markets disagree",
        "",
        f"Generated by `pipeline/gaps.py` on {date.today().isoformat()}.",
        "",
        "**How to read it.** Both columns give the chance that the non-Republican side wins: the Democrat, or in Nebraska the independent.",
        f"- **FLAG**: the gap is {FLAG:.0%} or more, so the race needs a manual review.",
        f"- **watch**: the gap is {WATCH:.0%} or more.",
        "- **Market margin**: the polling margin that would justify the market price.",
        "- **Hints**: computed automatically. They point to likely reasons, but they are not a verdict.",
        "",
        f"Races compared: {len(rows)} ({sum(r['race_id'].startswith('S-') for r in rows)} Senate, "
        f"{sum(r['race_id'].startswith('H-') for r in rows)} House). "
        f"Flagged: {sum(r['status'] == 'FLAG' for r in rows)}. Watch: {sum(r['status'] == 'watch' for r in rows)}.",
        "",
        "| Race | Status | Polls | Market | Gap | Poll margin | Market margin | Polls (45 days) | Latest poll | Traded | Hints |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        if r["status"] == "ok":
            continue
        lines.append(
            f"| {r['race_id']} | {r['status']} | {side(r['p_polls'])} | {side(r['p_market'])} | {r['gap']:+.0%} | "
            f"{margin(r['poll_margin'])} | {margin(r['market_implied_margin'])} | {r['n_polls_45d']} | {r['latest_poll']} | "
            f"${r['market_volume']:,} | {r['hints'] or '–'} |"
        )
    lines += ["", "## Manual review notes", "", "_To be written per flagged race: what explains the gap, and which side we believe._", ""]
    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"compared {len(rows)} races; flagged {sum(r['status'] == 'FLAG' for r in rows)}, watch {sum(r['status'] == 'watch' for r in rows)}")


if __name__ == "__main__":
    main()
